#!/usr/bin/env node
// Phase-1 client build: keep the DSH ModuleLoader contract (one client.js),
// but assemble it from small, scope-preserving source fragments.
//
// Fragments share the lexical scope of the ModuleLoader factory. This lets the
// existing component graph be split without an all-at-once ESM rewrite.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
// 片段列表由目录推导：新增/删除 parts 文件后必须自动进入产物，
// 否则会出现「源码有、产物无」→ 运行时 ReferenceError，整个插件加载失败。
const partsDir = path.join(root, 'src/client/parts');
const parts = fs.readdirSync(partsDir)
  .filter((f) => f.endsWith('.js'))
  .sort((a, b) => a.localeCompare(b, 'en'));
if (!parts.length) throw new Error('no client parts found in src/client/parts');

const pkg = JSON.parse(read('package.json'));

function build() {
  const tokensCss = read('src/client/styles/tokens.css').trimEnd();
  const mainCss = read('src/client/styles/main.css').trimEnd();
  const kitCss = read('src/client/styles/kit.css').trimEnd();
  const prelude = read('src/client/parts/00-prelude.js').trimEnd();

  const hashInputs = [pkg.version, ...parts.map((p) => read(`src/client/parts/${p}`)), tokensCss, mainCss, kitCss].join('\n---\n');
  const srcHash = crypto.createHash('sha1').update(hashInputs).digest('hex').slice(0, 12);
  let out = `// @generated by build/client.mjs — edit src/client/parts instead.\n`;
  out += `// @dsh-contextos-devops ${pkg.version}\n`;
  out += `// @build-hash ${srcHash}\n`;
  out += `// @parts ${parts.map((f) => f + ':' + crypto.createHash('sha256').update(read(`src/client/parts/${f}`)).digest('hex').slice(0, 8)).join(',')}\n`;
  out += prelude;
  fs.mkdirSync(path.join(root, 'assets'), { recursive: true });
  fs.writeFileSync(path.join(root, 'assets/client.css'), `${tokensCss}\n${mainCss}\n${kitCss}\n`);
  out += `\n    const CYBER_AVATAR = '/dsh-contextos-devops/assets/avatar.jpg?v=${pkg.version}';\n`;
  for (const part of parts.slice(1)) out += `\n${read(`src/client/parts/${part}`).trimEnd()}\n`;
  out += '\n';

  out = out.replaceAll('__CLIENT_CSS_VERSION__', pkg.version);
  out = out.replaceAll('__CLIENT_BUILD__', srcHash);
  fs.writeFileSync(path.join(root, 'client.js'), out);
  console.log(`[client] built client.js (${(Buffer.byteLength(out) / 1024).toFixed(1)} KB, ${parts.length} fragments)`);
}

build();

if (process.argv.includes('--watch')) {
  console.log('[client] watching src/client ...');
  let timer = null;
  try {
    fs.watch(path.join(root, 'src/client'), { recursive: true }, () => {
      clearTimeout(timer);
      timer = setTimeout(() => {
        try { build(); } catch (e) { console.error('[client] build failed:', e.message); }
      }, 120);
    });
  } catch (e) {
    console.error('[client] watch unavailable:', e.message);
  }
}
